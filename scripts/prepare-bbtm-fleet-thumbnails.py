"""Build small, content-addressed WebP thumbnails; never modify the supplied PNGs.

Run with Python + Pillow 12.3.0. Generated assets are committed, so neither Python
nor Pillow is required by the application build or in production.
"""
import argparse
import hashlib
import io
import json
import re
from pathlib import Path

from PIL import Image, ImageOps


def preserve_unselected(root, catalog, selected_slug):
    generated = (root / "src/features/fleet/fleetPhotoCatalog.ts").read_text(encoding="utf-8")
    match = re.search(r"export const BBTM_FLEET_PHOTOS = (\[.*?\]) as const;", generated, re.S)
    if not match:
        raise ValueError("Existing fleet catalog metadata is missing or invalid")
    previous = json.loads(match.group(1))
    by_slug = {photo["slug"]: photo for photo in previous}
    if len(by_slug) != len(previous):
        raise ValueError("Existing fleet catalog contains duplicate slugs")
    source_slugs = {photo["slug"] for photo in catalog}
    if len(source_slugs) != len(catalog) or not set(by_slug).issubset(source_slugs):
        raise ValueError("Source catalog contains duplicate slugs or would remove an existing illustration")
    for index, photo in enumerate(catalog):
        if photo["slug"] == selected_slug:
            continue
        saved = by_slug.get(photo["slug"])
        if not saved or any(saved.get(key) != value for key, value in photo.items()):
            raise ValueError(f'{photo["slug"]}: existing source metadata is missing or inconsistent')
        digest = saved.get("thumbnailSha256", "")
        if (not re.fullmatch(r"[0-9a-f]{64}", digest)
                or not re.fullmatch(r"[0-9a-f]{64}", saved.get("originalSha256", ""))
                or saved.get("thumbnail") != f'{photo["slug"]}-{digest[:16]}.webp'
                or not isinstance(saved.get("width"), int) or not 0 < saved["width"] <= 256
                or not isinstance(saved.get("height"), int) or not 0 < saved["height"] <= 171):
            raise ValueError(f'{photo["slug"]}: existing thumbnail metadata is inconsistent')
        data = (root / "public/vessels/bbtm" / saved["thumbnail"]).read_bytes()
        if (len(data) != saved.get("thumbnailBytes") or len(data) > 20_000
                or hashlib.sha256(data).hexdigest() != digest):
            raise ValueError(f'{photo["slug"]}: existing thumbnail is missing or inconsistent')
        catalog[index] = saved


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", required=True, type=Path)
    parser.add_argument("--only", help="Prepare one catalog slug and preserve the other illustrations")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    catalog = json.loads((root / "scripts/bbtm-fleet-photo-sources.json").read_text(encoding="utf-8"))
    if args.only is not None:
        if sum(photo["slug"] == args.only for photo in catalog) != 1:
            parser.error(f"--only must identify one existing catalog slug: {args.only}")
        preserve_unselected(root, catalog, args.only)
    target = root / "public/vessels/bbtm"
    target.mkdir(parents=True, exist_ok=True)
    originals_total = thumbnails_total = 0
    for photo in catalog:
        if args.only is not None and photo["slug"] != args.only:
            continue
        source = args.source_dir / photo["file"]
        original = source.read_bytes()
        with Image.open(source) as image:
            image = ImageOps.exif_transpose(image).convert("RGB")
            image.thumbnail((256, 171), Image.Resampling.LANCZOS)
            output = io.BytesIO()
            image.save(output, format="WEBP", quality=70, method=6)
            data = output.getvalue()
            if len(data) > 20_000:
                raise ValueError(f'{photo["file"]}: exceeds the 20 KB thumbnail budget')
            photo["width"], photo["height"] = image.size
        digest = hashlib.sha256(data).hexdigest()
        photo["thumbnail"] = f'{photo["slug"]}-{digest[:16]}.webp'
        photo["thumbnailBytes"] = len(data)
        photo["thumbnailSha256"] = digest
        photo["originalSha256"] = hashlib.sha256(original).hexdigest()
        (target / photo["thumbnail"]).write_bytes(data)
        originals_total += len(original)
        thumbnails_total += len(data)
    catalog_total = sum(photo["thumbnailBytes"] for photo in catalog)
    if catalog_total > 120_000:
        raise ValueError("Fleet thumbnails exceed the 120 KB total budget")
    generated = "// Generated by scripts/prepare-bbtm-fleet-thumbnails.py. Edit the source JSON.\n"
    generated += "// Originals live in private fleet-media; only these small thumbnails are public.\n"
    generated += "export const BBTM_FLEET_PHOTOS = " + json.dumps(catalog, ensure_ascii=False, indent=2) + " as const;\n\n"
    generated += "export function fleetCatalogThumbnailPath(photo: { thumbnail: string }): string {\n"
    generated += "  return `/vessels/bbtm/${photo.thumbnail}`;\n}\n"
    (root / "src/features/fleet/fleetPhotoCatalog.ts").write_text(generated, encoding="utf-8")
    print(json.dumps({"originalBytes": originals_total, "thumbnailBytes": thumbnails_total,
                      "catalogThumbnailBytes": catalog_total,
                      "reductionPercent": round(100 * (1 - thumbnails_total / originals_total), 2)}, indent=2))


if __name__ == "__main__":
    main()
