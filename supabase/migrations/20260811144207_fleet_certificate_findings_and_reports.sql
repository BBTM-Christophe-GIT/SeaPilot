create or replace function public.prepare_fleet_certificate_finding()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target_company_id bigint;
begin
  select certificate.company_id
  into target_company_id
  from public.fleet_certificates certificate
  where certificate.id = new.certificate_id
    and certificate.company_id = public.current_planning_company_id();

  if target_company_id is null then
    raise exception using errcode = '42501', message = 'Certificat inaccessible.';
  end if;

  new.company_id := target_company_id;
  new.created_by := coalesce(new.created_by, auth.uid());
  new.updated_by := auth.uid();
  new.updated_at := now();
  new.reference := coalesce(
    nullif(btrim(new.reference), ''),
    'EC-' || extract(year from new.detected_on)::integer::text || '-' || lpad(new.id::text, 4, '0')
  );
  new.responsible_name := coalesce((
    select btrim(concat(person.first_name, ' ', person.last_name))
    from public.people person
    where person.id = new.responsible_person_id
      and person.company_id = target_company_id
  ), nullif(btrim(new.responsible_name), ''), 'Non assigné');

  if new.status = 'closed' then
    new.progress := 100;
    new.closed_at := coalesce(new.closed_at, now());
  elsif new.progress = 100 and new.status <> 'pending_validation' then
    new.status := 'pending_validation';
  end if;

  return new;
end;
$$;

revoke all on function public.prepare_fleet_certificate_finding() from public, anon, authenticated;

create trigger fleet_certificate_findings_prepare
before insert or update on public.fleet_certificate_findings
for each row execute function public.prepare_fleet_certificate_finding();

create or replace function public.audit_fleet_certificate_finding()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.fleet_certificate_finding_events (
      company_id, finding_id, event_type, to_status, note, created_by
    ) values (
      new.company_id, new.id, 'created', new.status, 'Écart créé', auth.uid()
    );
    return new;
  end if;

  if old.responsible_person_id is distinct from new.responsible_person_id
    or old.responsible_name is distinct from new.responsible_name then
    insert into public.fleet_certificate_finding_events (
      company_id, finding_id, event_type, from_status, to_status, note, created_by
    ) values (
      new.company_id, new.id, 'assigned', old.status, new.status,
      'Responsable : ' || new.responsible_name, auth.uid()
    );
  end if;

  if old.status is distinct from new.status then
    insert into public.fleet_certificate_finding_events (
      company_id, finding_id, event_type, from_status, to_status, note, created_by
    ) values (
      new.company_id, new.id,
      case when new.status = 'closed' then 'validated' else 'status_changed' end,
      old.status, new.status, 'État mis à jour', auth.uid()
    );
  elsif old.progress is distinct from new.progress then
    insert into public.fleet_certificate_finding_events (
      company_id, finding_id, event_type, from_status, to_status, note, created_by
    ) values (
      new.company_id, new.id, 'progress_updated', old.status, new.status,
      'Avancement : ' || new.progress::text || ' %', auth.uid()
    );
  end if;

  return new;
end;
$$;

revoke all on function public.audit_fleet_certificate_finding() from public, anon, authenticated;

create trigger fleet_certificate_findings_audit
after insert or update on public.fleet_certificate_findings
for each row execute function public.audit_fleet_certificate_finding();

