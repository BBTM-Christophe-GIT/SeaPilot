create table public.fleet_certificate_findings (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  certificate_id bigint not null references public.fleet_certificates(id) on delete cascade,
  reference text not null,
  finding_type text not null check (finding_type in (
    'major_non_conformity',
    'minor_non_conformity',
    'class_condition',
    'remark',
    'prescription'
  )),
  title text not null check (length(btrim(title)) between 3 and 240),
  description text not null default '',
  detected_on date not null default current_date,
  treatment_delay_days integer check (treatment_delay_days is null or treatment_delay_days >= 0),
  treatment_due_on date,
  status text not null default 'declared' check (status in (
    'declared', 'assigned', 'in_progress', 'pending_validation', 'closed'
  )),
  progress smallint not null default 0 check (progress between 0 and 100),
  responsible_person_id bigint references public.people(id) on delete set null,
  responsible_name text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  updated_by uuid references public.profiles(id) on delete set null,
  validated_by uuid references public.profiles(id) on delete set null,
  validated_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, reference),
  unique (id, company_id)
);

create table public.fleet_certificate_finding_attachments (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  finding_id bigint not null,
  attachment_kind text not null check (attachment_kind in ('finding', 'treatment')),
  original_file_name text not null,
  storage_bucket text not null default 'fleet-certificates',
  storage_path text not null,
  mime_type text,
  file_size_bytes bigint check (file_size_bytes is null or file_size_bytes >= 0),
  caption text not null default '',
  uploaded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (storage_bucket, storage_path),
  constraint fleet_certificate_finding_attachments_finding_company_fk
    foreign key (finding_id, company_id)
    references public.fleet_certificate_findings(id, company_id)
    on delete cascade
);

create table public.fleet_certificate_finding_events (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  finding_id bigint not null,
  event_type text not null check (event_type in (
    'created', 'assigned', 'status_changed', 'progress_updated',
    'evidence_added', 'commented', 'validated'
  )),
  from_status text,
  to_status text,
  note text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint fleet_certificate_finding_events_finding_company_fk
    foreign key (finding_id, company_id)
    references public.fleet_certificate_findings(id, company_id)
    on delete cascade
);

