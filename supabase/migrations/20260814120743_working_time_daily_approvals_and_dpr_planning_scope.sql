-- Daily work-time submission/approval and Planning-backed DPR scope.
--
-- A monthly register remains the durable container, but workflow state is now
-- carried by each worked day. This prevents an early approval from locking the
-- remaining days of the month. Planning statuses are normalised server-side so
-- only personnel effectively "En mer" or "A terre" are considered on duty.

create or replace function public.planning_status_is_working(p_status text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(
    translate(upper(coalesce(p_status, '')),
      'ÀÁÂÃÄÅÇÈÉÊËÌÍÎÏÑÒÓÔÕÖÙÚÛÜÝ',
      'AAAAAACEEEEIIIINOOOOOUUUUY'),
    '[^A-Z0-9]+', '', 'g'
  ) in ('ENMER', 'ATERRE', 'EMBARQUE');
$$;

create or replace function public.planning_effective_person_status(
  p_company_id bigint,
  p_person_id bigint,
  p_work_date date,
  p_vessel_id bigint,
  p_fallback_status text default null
)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (
      select nullif(trim(day_status.sailor_status), '')
      from public.planning_days day_status
      where day_status.company_id = p_company_id
        and day_status.person_id = p_person_id
        and day_status.work_date = p_work_date
        and (p_vessel_id is null or day_status.vessel_id is null or day_status.vessel_id = p_vessel_id)
      order by (day_status.vessel_id = p_vessel_id) desc, day_status.id desc
      limit 1
    ),
    (
      select nullif(trim(period_status.sailor_status), '')
      from public.planning_periods period_status
      where period_status.company_id = p_company_id
        and period_status.person_id = p_person_id
        and p_work_date between period_status.starts_on and period_status.ends_on
        and (p_vessel_id is null or period_status.vessel_id is null or period_status.vessel_id = p_vessel_id)
      order by (period_status.vessel_id = p_vessel_id) desc, period_status.id desc
      limit 1
    ),
    nullif(trim(p_fallback_status), '')
  );
$$;

revoke all on function public.planning_status_is_working(text) from public, anon, authenticated;
revoke all on function public.planning_effective_person_status(bigint, bigint, date, bigint, text) from public, anon, authenticated;

