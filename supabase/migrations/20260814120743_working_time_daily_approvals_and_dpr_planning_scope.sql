  approver_person_id bigint references public.people(id) on delete restrict,
  submitted_by uuid references auth.users(id) on delete set null,
  submitted_by_person_id bigint references public.people(id) on delete set null,
  submitted_at timestamptz,
  validated_by uuid references auth.users(id) on delete set null,
  validated_by_person_id bigint references public.people(id) on delete set null,
  validated_at timestamptz,
  subject_identity_snapshot jsonb not null default '{}'::jsonb,
  approver_identity_snapshot jsonb not null default '{}'::jsonb,
  vessel_snapshot jsonb not null default '{}'::jsonb,
  watch_snapshot jsonb not null default '{}'::jsonb,
  signature_snapshot jsonb not null default '{}'::jsonb,
  interval_snapshot jsonb not null default '[]'::jsonb,
  non_compliance_snapshot jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint working_time_day_approvals_status_check
    check (status in ('draft', 'submitted', 'validated')),
  constraint working_time_day_approvals_submit_check check (
    status = 'draft'
    or (approver_person_id is not null and submitted_at is not null and submitted_by_person_id is not null)
  ),
  constraint working_time_day_approvals_validate_check check (
    status <> 'validated'
    or (validated_at is not null and validated_by_person_id is not null)
  ),
  constraint working_time_day_approvals_no_self_approval_check
    check (approver_person_id is null or approver_person_id <> person_id),
  unique (register_id, local_work_date)
);

