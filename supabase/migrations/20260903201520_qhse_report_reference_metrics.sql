create table if not exists public.qhse_annual_reference_metrics (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  report_year integer not null check (report_year between 2000 and 2200),
  vessel_id bigint references public.vessels(id) on delete cascade,
  worked_hours numeric(14, 2) not null check (worked_hours >= 0),
  person_days numeric(14, 2) not null check (person_days >= 0),
  source_label text not null,
  source_document text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists qhse_annual_reference_metrics_scope_idx
  on public.qhse_annual_reference_metrics (company_id, report_year, coalesce(vessel_id, 0));

create table if not exists public.qhse_environment_parameters (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  parameter_key text not null,
  label text not null,
  fuel_density_tonnes_per_m3 numeric(10, 6) not null check (fuel_density_tonnes_per_m3 > 0),
  emission_factor_tco2_per_tonne numeric(10, 6) not null check (emission_factor_tco2_per_tonne > 0),
  xbee_reduction_rate numeric(8, 6) not null check (xbee_reduction_rate between 0 and 1),
  effective_from date not null,
  effective_to date,
  applies_to_all_vessels boolean not null default true,
  source_label text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, parameter_key, effective_from),
  check (effective_to is null or effective_to >= effective_from)
);

create table if not exists public.qhse_contract_targets (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  project_id bigint not null references public.projects(id) on delete cascade,
  vessel_id bigint not null references public.vessels(id) on delete cascade,
  report_year integer not null check (report_year between 2000 and 2200),
  maintenance_days_limit numeric(8, 2) not null check (maintenance_days_limit >= 0),
  port_call_24h_limit integer not null check (port_call_24h_limit >= 0),
  valid_until date,
  source_label text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, project_id, vessel_id, report_year)
);

