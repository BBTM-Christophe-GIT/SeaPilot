    port_call_24h_limit = excluded.port_call_24h_limit,
    valid_until = excluded.valid_until,
    source_label = excluded.source_label,
    updated_at = now();

create or replace function public.qhse_set_employment_population_from_grade()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  normalized_grade text;
begin
  normalized_grade := translate(
    lower(coalesce(new.grade_label, '')),
    'éèêëàâäîïôöùûüç',
    'eeeeaaaiioouuuc'
  );
  new.employment_population := case
    when normalized_grade like '%sedentaire%' then 'sedentary'
    else 'offshore'
  end;
  return new;
end;
$$;

revoke all on function public.qhse_set_employment_population_from_grade() from public, anon, authenticated;

drop trigger if exists qhse_people_population_from_grade on public.people;
create trigger qhse_people_population_from_grade
before insert or update of grade_label on public.people
for each row execute function public.qhse_set_employment_population_from_grade();

update public.people
set employment_population = case
  when translate(lower(coalesce(grade_label, '')), 'éèêëàâäîïôöùûüç', 'eeeeaaaiioouuuc') like '%sedentaire%'
    then 'sedentary'
  else 'offshore'
end;

