create function public.save_organigramme_watch(p_chart_id bigint, p_id bigint, p_vessel_id bigint, p_name text, p_members jsonb, p_revision integer default null)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare
  company bigint := public.current_planning_company_id();
  today date := (now() at time zone 'Europe/Paris')::date;
  saved bigint;
begin
  if public.organigramme_has_access(company) is not true then
    raise exception 'Accès refusé à l’organigramme.' using errcode = '42501';
  end if;
  perform 1 from public.organigramme_charts where company_id = company and id = p_chart_id for update;
  if not found then raise exception 'Organigramme introuvable.' using errcode = 'P0002'; end if;

  if p_members is null or jsonb_typeof(p_members) <> 'array' then
    raise exception 'Composition invalide.' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.vessels where id = p_vessel_id and company_id = company and asset_kind = 'vessel' and active
      and (fleet_exit_on is null or fleet_exit_on > today)
  ) then raise exception 'Navire indisponible.' using errcode = '42501'; end if;
  if exists (
    select 1 from jsonb_to_recordset(p_members) as member("personId" bigint)
    where not exists (
      select 1 from public.people p where p.id = member."personId" and p.company_id = company and p.active
        and (p.hired_on is null or p.hired_on <= today) and (p.departed_on is null or p.departed_on > today)
    )
  ) then raise exception 'Personne indisponible dans cette société.' using errcode = '42501'; end if;

  if p_id is null then
    insert into public.organigramme_watches (company_id, chart_id, vessel_id, name)
    values (company, p_chart_id, p_vessel_id, btrim(p_name)) returning id into saved;
  else
    update public.organigramme_watches set vessel_id = p_vessel_id, name = btrim(p_name), revision = revision + 1
    where id = p_id and company_id = company and chart_id = p_chart_id and (p_revision is null or revision = p_revision)
    returning id into saved;
    if not found then
      if exists (select 1 from public.organigramme_watches where id = p_id and company_id = company and chart_id = p_chart_id) then
        raise exception 'Cette bordée a été modifiée. Actualisez avant de reprendre la composition.' using errcode = '40001';
      end if;
      raise exception 'Bordée introuvable.' using errcode = 'P0002';
    end if;
  end if;
  if exists (
    select 1 from jsonb_to_recordset(p_members) as member("personId" bigint)
    join public.organigramme_watch_members m on m.company_id = company and m.person_id = member."personId"
    join public.organigramme_watches w on w.id = m.watch_id and w.company_id = m.company_id
    where w.chart_id = p_chart_id and w.id <> saved and not exists (
      select 1 from public.organigramme_watch_members existing
      where existing.watch_id = saved and existing.person_id = member."personId"
    )
  ) then raise exception 'Un collaborateur figure déjà dans une autre bordée.' using errcode = '23505'; end if;

  delete from public.organigramme_watch_members where watch_id = saved and company_id = company;
  insert into public.organigramme_watch_members (company_id, watch_id, person_id, function_label)
  select company, saved, m."personId", coalesce(btrim(m."functionLabel"), '')
  from jsonb_to_recordset(p_members) as m("personId" bigint, "functionLabel" text);
  return saved;
end;
$$;

create function public.save_organigramme_responsibility(p_chart_id bigint, p_id bigint, p_person_id bigint, p_name text,
  p_function_label text, p_category text, p_position integer, p_rank text)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare
  company bigint := public.current_planning_company_id();
  rank text := case when p_category = 'office' then nullif(p_rank, '') end;
  saved bigint;
begin
  if public.organigramme_has_access(company) is not true then
    raise exception 'Accès refusé à l’organigramme.' using errcode = '42501';
  end if;
  if p_id is null then
    insert into public.organigramme_support (company_id, chart_id, person_id, name, function_label, category, position, hierarchy_rank)
    values (company, p_chart_id, p_person_id, btrim(p_name), btrim(p_function_label), p_category, p_position, rank)
    returning id into saved;
  else
    update public.organigramme_support set person_id = p_person_id, name = btrim(p_name), function_label = btrim(p_function_label),
      category = p_category, position = p_position, hierarchy_rank = rank
    where id = p_id and company_id = company and chart_id = p_chart_id returning id into saved;
    if not found then raise exception 'Intervenant introuvable.' using errcode = 'P0002'; end if;
  end if;
  return saved;
end;
$$;

