-- Negative person keys refer to free-text support entries in the same chart.
create function public.organigramme_target_allowed(company bigint, chart bigint, kind text, key text, section text)
returns boolean language sql stable security invoker set search_path = '' as $$
  select public.organigramme_target_allowed(company, kind, key, section)
    and case
      when kind = 'person' and key ~ '^-[1-9][0-9]{0,17}$' then exists (
        select 1 from public.organigramme_support s
        where s.company_id = company and s.chart_id = chart and s.id = -(key::bigint) and s.person_id is null
      )
      when kind = 'person' and key ~ '^[1-9][0-9]{0,17}$' then private.organigramme_person_allowed(company, key::bigint)
      else true
    end;
$$;
