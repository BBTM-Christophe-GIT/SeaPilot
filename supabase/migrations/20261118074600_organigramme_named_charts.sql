create function public.create_organigramme_chart(p_name text)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare
  company bigint := public.current_planning_company_id();
  today date := (now() at time zone 'Europe/Paris')::date;
  chart bigint;
begin
  if public.organigramme_has_access(company) is not true then
    raise exception 'Accès refusé à l’organigramme.' using errcode = '42501';
  end if;
  insert into public.organigramme_charts (company_id, name)
  values (company, btrim(p_name)) returning id into chart;
  insert into public.organigramme_watches (company_id, chart_id, vessel_id, name)
  select company, chart, vessel.id, watch.name
  from public.vessels vessel cross join (values ('Bordée 1'), ('Bordée 2')) watch(name)
  where vessel.company_id = company and vessel.asset_kind = 'vessel' and vessel.active
    and (vessel.fleet_exit_on is null or vessel.fleet_exit_on > today);
  return chart;
end;
$$;

create function public.rename_organigramme_chart(p_chart_id bigint, p_name text)
returns void language plpgsql security invoker set search_path = '' as $$
declare company bigint := public.current_planning_company_id();
begin
  if public.organigramme_has_access(company) is not true then
    raise exception 'Accès refusé à l’organigramme.' using errcode = '42501';
  end if;
