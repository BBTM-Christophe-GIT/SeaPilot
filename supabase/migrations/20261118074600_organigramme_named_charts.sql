-- Chart 0 is the existing organigramme. Keep its row IDs and old client entry points.
create table public.organigramme_charts (
  company_id bigint not null default public.current_planning_company_id() references public.companies(id) on delete cascade,
  id bigint generated by default as identity check (id >= 0),
  name text not null check (length(btrim(name)) between 1 and 100 and name = btrim(name)),
  primary key (company_id, id)
);
create unique index organigramme_charts_name_idx on public.organigramme_charts (company_id, lower(name));

insert into public.organigramme_charts (company_id, id, name)
select id, 0, 'Organigramme principal' from public.companies;

